# gen-issue-forms.sh — generate .github/ISSUE_TEMPLATE/error_report.yml from src/errors/errors.toml,
# so the error-ID dropdown can never drift from the taxonomy. `--check` exits 1 on drift.
set -euo pipefail
R=$(cd "$(dirname "$0")/.." && pwd); out="$R/.github/ISSUE_TEMPLATE/error_report.yml"
ids=$("$R/scripts/lib/toml2json.sh" "$R/src/errors/errors.toml" | jq -r '.error[] | "        - \"\(.id) (exit \(.exit)): \(.meaning | gsub("\""; "'"'"'"))\""')
new=$(cat <<YAML
# SPDX-License-Identifier: CC-BY-SA-4.0
# SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell <j.d.a.jewell@open.ac.uk>
# GENERATED by scripts/gen-issue-forms.sh from src/errors/errors.toml — edit the TOML, not this file.
name: idris2x printed an error
description: idris2x stopped with an error ID (E-...). Start here; it is the fastest way to a fix.
title: "[E-???] <one line: what you ran and what happened>"
labels: ["bug", "needs-triage", "error-report"]
body:
  - type: markdown
    attributes:
      value: |
        Every idris2x failure has a stable ID, an exit code and a runbook. Please check the runbook linked in the
        error first: most reports are solved by its fix line. If it did not help, this form gives us everything
        we need in one round trip.
  - type: dropdown
    id: error-id
    attributes:
      label: Error ID
      description: The E-... code idris2x printed (also its exit code).
      options:
$ids
        - "No error ID was printed (that itself is a bug: every failure must be typed)"
    validations:
      required: true
  - type: textarea
    id: command
    attributes:
      label: The exact command and its full output
      render: shell
      placeholder: |
        \$ idris2x exec --locked -- idris2 --check src/Main.idr
        idris2x: E-HASH-MISMATCH: ...
    validations:
      required: true
  - type: textarea
    id: doctor
    attributes:
      label: Output of idris2x doctor --json
      description: Contains no secrets and no telemetry; review it before pasting if you are unsure.
      render: json
    validations:
      required: true
  - type: textarea
    id: lock
    attributes:
      label: idris2x.lock (if the project has one)
      render: json
  - type: dropdown
    id: context
    attributes:
      label: Where did this happen?
      options: ["Developer laptop", "CI runner (GitHub-hosted)", "CI runner (self-hosted)", "Server or container", "Air-gapped host", "Other"]
    validations:
      required: true
  - type: checkboxes
    id: checked
    attributes:
      label: Before submitting
      options:
        - label: I read the runbook linked in the error message.
          required: true
        - label: I did not paste any credentials, tokens or private paths I mind sharing.
          required: true
YAML
)
if [ "${1:-}" = --check ]; then [ "$(cat "$out" 2>/dev/null)" = "$new" ] && echo "error_report.yml up to date" || { echo "error_report.yml is stale: run scripts/gen-issue-forms.sh"; exit 1; }
else printf '%s\n' "$new" > "$out"; echo "wrote $out"; fi
