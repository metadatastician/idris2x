#!/usr/bin/env bash
# SPDX-License-Identifier: MPL-2.0 AND CC-BY-SA-4.0
# This script is MPL-2.0. The message wording it copies into src/errors_gen.rs is CC-BY-SA-4.0.
# gen-errors-rs.sh — generate the launcher's message table, src/errors_gen.rs, from src/errors/errors.toml.
# One `Fail` variant per [[case]], with one named field per {placeholder}, so a missing value is a compile error.
# Each field's type is the slot class ADR 0012 allows for it: a key in any prose slot is `Prose`, else a key in the
# fix command is `Fix`, else it is a `Fact`. The text of `idris2x explain` is built here, with the prototype's jq,
# because it depends on nothing but the TOML. `--check` exits 1 if the file would change. Needs only bash and jq.
set -euo pipefail
R=$(cd "$(dirname "$0")/.." && pwd); out="$R/src/errors_gen.rs"
check=0; [ "${1:-}" = --check ] && check=1
new=$("$R/scripts/lib/toml2json.sh" "$R/src/errors/errors.toml" | jq -r '
def lit: if test("[\u0000-\u0008\u000b-\u001f\u007f]") then error("control character in errors.toml text: " + tojson) else tojson end;
def S: "&\u0027static str";
def camel: split("-") | map((.[0:1] | ascii_upcase) + .[1:]) | join("");
def variant: (.error[2:] | ascii_downcase | camel) + (.case | camel);
def keys_in: [scan("\\{([a-z_]+)\\}") | .[0]];
def uniq: reduce .[] as $k ([]; if any(.[]; . == $k) then . else . + [$k] end);
def keys: ((.facts | split(" ") | map(select(. != "") | split("=") | .[1]))
  + ([.summary, .story, .state, .why, .fix_lead, .fix_cmd, .fix_note] | map(keys_in) | add) | uniq);
def ctx($ks): "vec![\($ks | map("(\(lit), &*\(.).0)") | join(", "))]";
. as $all | (.error | map(.id)) as $ids
| "// SPDX-License-Identifier: MPL-2.0 AND CC-BY-SA-4.0",
  "// The code is MPL-2.0. The message wording, copied from src/errors/errors.toml, is CC-BY-SA-4.0.",
  "// GENERATED by scripts/gen-errors-rs.sh from src/errors/errors.toml. Do not edit: change the TOML and run the script.",
  "// Included by src/msg.rs, so the slot classes keep their fields private to that module.",
  "",
  "/// One `[[error]]`. `explain` is the text of `idris2x explain ID` up to its runbook line.",
  "pub(crate) struct ErrorDef { id: \(S), title: \(S), exit: u8, explain: \(S) }",
  "/// One `[[case]]`: its error (an index into `ERRORS`), its templates, and its facts as (label, key).",
  "pub(crate) struct CaseDef {",
  "    error: usize, case: \(S), summary: \(S), story: \(S), facts: &\u0027static [(\(S), \(S))], state: \(S),",
  "    why: \(S), fix_lead: \(S), fix_cmd: \(S), fix_note: \(S), auto: \(S),",
  "}",
  "/// One `[[advice]]`: a note that is not an error, and the variable that silences it.",
  "pub(crate) struct AdviceDef { text: \(S), silence: \(S) }",
  "",
  "/// The text of `idris2x explain` with no id: one line per error.",
  "pub(crate) static EXPLAIN_ALL: &str = \([.error[] | .id + (" " * (24 - (.id | length))) + "exit " + (.exit | tostring | (" " * (2 - length)) + .) + "  " + (.title // .meaning) + "\n"] | add | lit);",
  "",
  "pub(crate) static ERRORS: [ErrorDef; \(.error | length)] = [",
  (.error[] | . as $e | [$all.case[] | select(.error == $e.id)] as $c
   | ([ "\($e.id) (exit \($e.exit)): \($e.title // $e.meaning)", "", "Meaning: \($e.meaning)", "Usual fix: \($e.fix)",
        (if ($c | length) > 0 then "", "It takes \($c | length) shape(s). Words in {braces} are filled in when it happens.",
           ($c[] | "", "  \(.case): \(.summary)", "    why: \(.why)", "    now: \(.state)",
              (if .fix_cmd != "" then "    fix: \(.fix_cmd)" else empty end), (if .fix_note != "" then "    note: \(.fix_note)" else empty end))
         else empty end), "" ] | map(. + "\n") | add) as $x
   | "    ErrorDef { id: \(.id | lit), title: \(.title | lit), exit: \(.exit), explain: \($x | lit) },"),
  "];",
  "",
  "pub(crate) static CASES: [CaseDef; \(.case | length)] = [",
  (.case[] | . as $c
   | if ($c.auto | test("[{]")) then error("auto may not hold a placeholder: " + $c.error + "/" + $c.case) else . end
   | ($ids | index($c.error) // error("case names an unknown error: " + $c.error)) as $e
   | ($c.facts | split(" ") | map(select(. != "") | split("=") | "(\(.[0] | lit), \(.[1] | lit))") | join(", ")) as $facts
   | "    CaseDef { error: \($e), case: \($c.case | lit), summary: \($c.summary | lit), story: \($c.story | lit), facts: &[\($facts)],",
     "        state: \($c.state | lit), why: \($c.why | lit), fix_lead: \($c.fix_lead | lit), fix_cmd: \($c.fix_cmd | lit),",
     "        fix_note: \($c.fix_note | lit), auto: \($c.auto | lit) },"),
  "];",
  "",
  "pub(crate) static ADVICE: [AdviceDef; \(.advice | length)] = [",
  (.advice[] | "    AdviceDef { text: \(.text | lit), silence: \(.silence | lit) },"),
  "];",
  "",
  "/// Every way the launcher can fail: one variant per `[[case]]` in errors.toml.",
  "pub enum Fail {",
  (.case[] | . as $c
   | ([$c.summary, $c.story, $c.state, $c.why, $c.fix_lead, $c.fix_note] | map(keys_in) | add) as $prose
   | ($c.fix_cmd | keys_in) as $fix
   | "    /// \($c.error), case `\($c.case)`.",
     "    \($c | variant) { \($c | keys | map(. as $k | "\($k): " + (if any($prose[]; . == $k) then "Prose" elif any($fix[]; . == $k) then "Fix" else "Fact" end)) | join(", ")) },"),
  "}",
  "",
  "/// Every note that is not an error: one variant per `[[advice]]`. Its words are prose.",
  "pub enum Advice {",
  (.advice[] | "    \(.id | camel) { \(.text | keys_in | uniq | map("\(.): Prose") | join(", ")) },"),
  "}",
  "",
  "impl Fail {",
  "    /// The index of this case in `CASES`, and its context values in field order.",
  "    fn parts(&self) -> (usize, Vec<(\(S), &str)>) {",
  "        match self {",
  (.case | to_entries[] | .key as $i | .value | keys as $ks
   | "            Fail::\(variant) { \($ks | join(", ")) } => (\($i), \(ctx($ks))),"),
  "        }",
  "    }",
  "}",
  "",
  "impl Advice {",
  "    /// The index of this note in `ADVICE`, and its context values.",
  "    fn parts(&self) -> (usize, Vec<(\(S), &str)>) {",
  "        match self {",
  (.advice | to_entries[] | .key as $i | .value | (.text | keys_in | uniq) as $ks
   | "            Advice::\(.id | camel) { \($ks | join(", ")) } => (\($i), \(ctx($ks))),"),
  "        }",
  "    }",
  "}"')
if [ $check = 1 ]; then
  if [ -f "$out" ] && [ "$(cat "$out")" = "$new" ]; then echo "gen-errors-rs: src/errors_gen.rs matches errors.toml"
  else echo "gen-errors-rs: src/errors_gen.rs is stale (run scripts/gen-errors-rs.sh and commit the result)" >&2; exit 1; fi
else printf '%s\n' "$new" > "$out"; echo "wrote $out"; fi
